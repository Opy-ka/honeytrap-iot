import { ml_kem512 } from '@noble/post-quantum/ml-kem.js';
import { ml_dsa44 } from '@noble/post-quantum/ml-dsa.js';
import fs from 'fs';
import path from 'path';

// 1. Generate Server ML-KEM-512 Keypair (untuk Key Encapsulation)
const kemKeys = ml_kem512.keygen();

// 2. Generate ESP32 ML-DSA-44 Keypair (untuk Digital Signature)
const dsaKeys = ml_dsa44.keygen();

// Simpan ke pqc-gateway/keys.json (dipakai oleh server/gateway)
const serverKeys = {
  kem: {
    algorithm: 'ML-KEM-512',
    publicKeyBase64: Buffer.from(kemKeys.publicKey).toString('base64'),
    secretKeyBase64: Buffer.from(kemKeys.secretKey).toString('base64'),
  },
  dsa: {
    algorithm: 'ML-DSA-44',
    publicKeyBase64: Buffer.from(dsaKeys.publicKey).toString('base64'),
    secretKeyBase64: Buffer.from(dsaKeys.secretKey).toString('base64'),
  }
};

fs.writeFileSync('keys.json', JSON.stringify(serverKeys, null, 2));

// Helper format C byte array
function toCArray(name, uint8Arr) {
  const hex = Array.from(uint8Arr).map(b => '0x' + b.toString(16).padStart(2, '0'));
  const lines = [];
  for (let i = 0; i < hex.length; i += 16) {
    lines.push('  ' + hex.slice(i, i + 16).join(', '));
  }
  return `const uint8_t ${name}[${uint8Arr.length}] = {\n${lines.join(',\n')}\n};`;
}

// Simpan ke esp32_honeytrap/pqc_keys.h (dipakai oleh ESP32)
const headerContent = `// AUTO-GENERATED BY pqc-gateway/keygen.mjs
// JANGAN UBAH MANUAL — HARUS COCOK DENGAN pqc-gateway/keys.json
#ifndef PQC_KEYS_H
#define PQC_KEYS_H

#include <stdint.h>

// Public Key Server (ML-KEM-512, 800 bytes) -> dipakai ESP32 untuk enkapsulasi kunci AES-256
${toCArray('SERVER_KEM_PUBLIC_KEY', kemKeys.publicKey)}

// Secret Key ESP32 (ML-DSA-44, 2560 bytes) -> dipakai ESP32 untuk tanda tangan digital
${toCArray('ESP32_DSA_SECRET_KEY', dsaKeys.secretKey)}

#endif
`;

const espHeaderPath = path.resolve('..', 'esp32_honeytrap', 'pqc_keys.h');
fs.writeFileSync(espHeaderPath, headerContent);

console.log('SUCCESS: Kunci ML-KEM-512 & ML-DSA-44 berhasil dibuat!');
console.log(' -> Server keys : pqc-gateway/keys.json');
console.log(' -> ESP32 header: esp32_honeytrap/pqc_keys.h');
